#!/usr/bin/env python3
"""Generate the C++ mirrors of the engine-core config dataclasses (c1-mega, 14 Nov 2026; stage 2, fpr_core.h).

  fpr/core/include/geometry.h      <- serve/geometry.py: the model / page constants, PoolSpec, Geometry (every field, the
                                      same defaults) + rows_per_decode_seq / rows_cap / pools() (SmallGeometry: pool_override)
  fpr/core/include/sched_config.h  <- serve/scheduler.py SchedConfig
  fpr/core/include/cost_params.h   <- serve/cost_model.py CostParams + the module constants and ENGINE_MEASURED_* presets

Each struct has visit(c, v): v(python_name, member) for every field, in declaration order, so loaders (golden-trace
replays, PHYS_SCHED-style overrides) set fields by their Python names. Floats are written as Python repr (exact).
  python3 fpr/core/tools/gen_geometry.py [--check]      (--check: exit 1 if a generated file is stale)
"""
from __future__ import annotations

import dataclasses
import hashlib
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.normpath(os.path.join(HERE, ".."))
FPR = os.path.normpath(os.path.join(CORE, ".."))
SERVE = os.path.join(FPR, "serve")
INC = os.path.join(CORE, "include")
sys.path.insert(0, SERVE)

import cost_model  # noqa: E402
import geometry  # noqa: E402
import scheduler  # noqa: E402


def md5(p: str) -> str:
    return hashlib.md5(open(p, "rb").read()).hexdigest()[:8]


def cxx_type(v) -> str:
    if isinstance(v, bool):
        return "bool"
    if isinstance(v, int):
        return "int64_t"
    if isinstance(v, float):
        return "double"
    if isinstance(v, str):
        return "std::string"
    raise TypeError(f"unsupported default {v!r}")


def cxx_value(v, t: str) -> str:
    if t == "bool":
        return "true" if v else "false"
    if t == "std::string":
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if t == "double":
        v = float(v)
        if math.isinf(v):
            return ("-" if v < 0 else "") + "std::numeric_limits<double>::infinity()"
        return repr(v)
    return str(int(v))


def fields(cls) -> list:
    out = []
    for f in dataclasses.fields(cls):
        if f.default is not dataclasses.MISSING:
            v = f.default
        elif f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            v = f.default_factory()  # type: ignore[misc]
        else:
            raise TypeError(f"{cls.__name__}.{f.name}: no default")
        out.append((f.name, v, cxx_type(v)))
    return out


def struct(name: str, cls, doc: str, extra: list = (), skip_visit: tuple = ()) -> list:
    fs = fields(cls)
    out = [f"// {doc}", f"struct {name} {{"]
    for n, v, t in fs:
        out.append(f"  {t} {n} = {cxx_value(v, t)};")
    out += list(extra)
    out += ["", "  // every field with its Python name, in declaration order: v(const char* name, T& member)",
            "  template <class C, class V> static void visit(C& c, V&& v) {"]
    out += [f'    v("{n}", c.{n});' for n, _, _ in fs if n not in skip_visit]
    out += ["  }", "};"]
    return out


def header(lines: list, sources: list, includes=("<cstdint>", "<limits>", "<string>")) -> str:
    src = ", ".join(f"{os.path.relpath(p, FPR)} {md5(p)}" for p in sources)
    return "\n".join([
        f"// GENERATED by fpr/core/tools/gen_geometry.py from {src}. OWNER: c1-mega. Do not edit: re-run the generator.",
        "// Build: -O2 -std=c++17 -ffp-contract=off.",
        "#pragma once",
        *[f"#include {i}" for i in includes],
        "",
        "namespace fpr {",
        "",
        *lines,
        "",
        "}  // namespace fpr",
        "",
    ])


def gen() -> dict:
    sch, geo, cmo = (os.path.join(SERVE, f) for f in ("scheduler.py", "geometry.py", "cost_model.py"))
    g = geometry
    gl = [
        "// serve/geometry.py model / page constants (SLIDING_WINDOW, PAGE_TOKENS, WINDOW_PAGE_TOKENS: common.h)",
        f"constexpr int N_LAYERS = {g.N_LAYERS};",
        f"constexpr int HIDDEN = {g.HIDDEN};",
        f"constexpr int N_HEADS = {g.N_HEADS};",
        f"constexpr int LAST_KV_SOURCE = {g.LAST_KV_SOURCE};",
        f"constexpr int KV_SOURCE_LAYERS[{len(g.KV_SOURCE_LAYERS)}] = {{{', '.join(map(str, g.KV_SOURCE_LAYERS))}}};",
        f"constexpr int KV_SOURCE_RATIO[{len(g.KV_SOURCE_LAYERS)}] = "
        f"{{{', '.join(str(g.KV_SOURCE_RATIO[s]) for s in g.KV_SOURCE_LAYERS)}}};   // per KV_SOURCE_LAYERS entry",
        f"constexpr int CANDIDATE_LAYERS[{len(g.CANDIDATE_LAYERS)}] = {{{', '.join(map(str, g.CANDIDATE_LAYERS))}}};",
        f"constexpr int CANDIDATES = {g.CANDIDATES};",
        f"constexpr int SPEC_K = {g.SPEC_K};",
        f"constexpr int64_t MAX_MODEL_LEN = {g.MAX_MODEL_LEN};",
        f"constexpr int64_t PAGE_BYTES = {g.PAGE_BYTES};",
        f"constexpr int64_t WINDOW_PAGE_BYTES = {g.WINDOW_PAGE_BYTES};",
        f"constexpr int64_t STATE_SLOT_BYTES = {g.STATE_SLOT_BYTES};",
        "",
        "// serve/geometry.py PoolSpec (kind: \"paged\" | \"window\" | \"state\"; index = CopyOp.pool)",
        "struct PoolSpec { std::string name, kind; int64_t tokens_per_page, bytes_per_page, num_pages; };",
        "",
    ]
    extra = [
        "",
        "  // SmallGeometry (tests) / any other subclass: its pools() exactly; empty = Geometry.pools()",
        "  std::vector<PoolSpec> pool_override;",
        "",
        "  int64_t rows_per_decode_seq() const { return spec_k + 1; }",
        "  int64_t rows_cap() const {",
        "    return max_rows_per_rank ? max_rows_per_rank : rows_per_decode_seq() * max_seqs_per_rank + max_prefill_tokens_per_rank;",
        "  }",
        "  std::vector<PoolSpec> pools() const {",
        "    if (!pool_override.empty()) return pool_override;",
        "    int64_t num = kv_bytes_per_rank - window_pool_bytes - state_pool_slots * STATE_SLOT_BYTES;",
        "    int64_t n_pages = num / PAGE_BYTES - ((num % PAGE_BYTES != 0 && num < 0) ? 1 : 0);      // Python //",
        "    int64_t wn = window_pool_bytes / WINDOW_PAGE_BYTES - ((window_pool_bytes % WINDOW_PAGE_BYTES != 0 && window_pool_bytes < 0) ? 1 : 0);",
        "    return {PoolSpec{\"paged\", \"paged\", page_tokens, PAGE_BYTES, n_pages},",
        "            PoolSpec{\"window\", \"window\", window_page_tokens, WINDOW_PAGE_BYTES, wn},",
        "            PoolSpec{\"state\", \"state\", 0, STATE_SLOT_BYTES, state_pool_slots}};",
        "  }",
    ]
    geo_h = header(gl + struct("Geometry", geometry.Geometry, "serve/geometry.py Geometry, field for field", extra),
                   [geo], ("<cstdint>", "<limits>", "<string>", "<vector>"))
    sc_h = header(struct("SchedConfig", scheduler.SchedConfig,
                         "serve/scheduler.py SchedConfig, field for field (same names, same defaults)"), [sch])
    cm = cost_model
    cl = [
        "// serve/cost_model.py module constants",
        f"constexpr int COST_N_A = {cm.N_A};                 // layers 0..LAST_KV_SOURCE: every prefill row",
        f"constexpr int COST_N_B = {cm.N_B};                 // layers 21..39",
        f"constexpr double FULL_POS_PER_CTX = {cm.FULL_POS_PER_CTX!r};",
        f"constexpr int N_CAND_LAYERS = {cm.N_CAND_LAYERS};",
        f"constexpr int64_t CAND_SCORED = {cm.CAND_SCORED};",
        f"constexpr int N_KV_SOURCE_LAYERS = {len(geometry.KV_SOURCE_LAYERS)};",
        f"constexpr double BX_PREFILL_SCALE = {cm.BX_PREFILL_SCALE!r}, B8_PREFILL_SCALE = {cm.B8_PREFILL_SCALE!r};",
        "",
    ]
    presets = []
    for nm in ("ENGINE_MEASURED_1735", "ENGINE_MEASURED_2026_11_07"):
        d = getattr(cm, nm)
        body = " ".join(f"p.{k} = {v!r};" for k, v in d.items())
        presets.append(f"inline CostParams {nm}() {{ CostParams p; {body} return p; }}")
    cp_h = header(cl + struct("CostParams", cm.CostParams, "serve/cost_model.py CostParams, field for field")
                  + ["", "// cost_model.py presets (dicts of CostParams overrides)"] + presets, [cmo])
    return {os.path.join(INC, "geometry.h"): geo_h, os.path.join(INC, "sched_config.h"): sc_h,
            os.path.join(INC, "cost_params.h"): cp_h}


def main() -> int:
    check = "--check" in sys.argv
    bad = 0
    for path, text in gen().items():
        cur = open(path).read() if os.path.exists(path) else None
        if check:
            if cur != text:
                print(f"STALE {path}")
                bad = 1
            continue
        if cur != text:
            tmp = os.path.join(os.path.dirname(path), "." + os.path.basename(path) + ".new")
            with open(tmp, "w") as f:
                f.write(text)
            os.replace(tmp, path)
            print(f"wrote {path}")
        else:
            print(f"unchanged {path}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
